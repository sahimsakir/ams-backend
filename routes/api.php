    Route::post('/teams', [C::class, 'saveTeam'])->middleware('permission:teams.create');
    Route::put('/teams/{id}/members', [C::class, 'members'])->middleware('permission:teams.members_update');
    Route::get('/users', [C::class, 'users'])->middleware('permission:users.view');
    Route::post('/users/import', [C::class, 'importUsers'])->middleware('permission:users.import');
    Route::delete('/users/{id}', [C::class, 'deleteUser'])->middleware('permission:users.delete');
    Route::get('/applications/{id}/document', [C::class, 'document'])->middleware('permission:applications.document_view');
    Route::post('/users', [C::class, 'saveUser']);
    Route::put('/users/{id}', [C::class, 'saveUser']);
