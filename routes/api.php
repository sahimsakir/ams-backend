    Route::get('/attendance', [C::class, 'attendance'])->middleware('permission:attendance.view|attendance.view_team|attendance.view_all');
    Route::post('/attendance', [C::class, 'punch'])->middleware('throttle:ams-face');
    Route::get('/attendance/{id}/photo/{side}', [C::class, 'photo'])->middleware('permission:attendance.photo_view_self|attendance.photo_view_team|attendance.photo_view_all');
