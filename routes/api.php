<?php

use App\Http\Controllers\AccessController;
use App\Http\Controllers\AmsController as C;
use App\Http\Controllers\FaceController;
use Illuminate\Support\Facades\Route;

Route::get('/csrf-cookie', fn () => response()->json(['message' => 'CSRF cookie initialized']));
Route::post('/login', [C::class, 'login'])->middleware('throttle:ams-login');
Route::middleware(['token', 'throttle:ams-api'])->group(function () {
    Route::apiResource('roles', AccessController::class)->except(['show'])->parameters(['roles' => 'id']);
    Route::get('/permissions', [AccessController::class, 'permissions']);
    Route::post('/permissions', [AccessController::class, 'savePermission']);
    Route::put('/permissions/{id}', [AccessController::class, 'savePermission']);
    Route::delete('/permissions/{id}', [AccessController::class, 'deletePermission']);
    Route::put('/users/{id}/access', [AccessController::class, 'assign']);
    Route::get('/me', [C::class, 'me']);
    Route::post('/logout', [C::class, 'logout']);
    Route::put('/password', [C::class, 'password']);
    Route::get('/dashboard', [C::class, 'dashboard'])->middleware('permission:dashboard.view');
    Route::get('/applications', [C::class, 'applications'])->middleware('permission:applications.view');
    Route::post('/applications', [C::class, 'apply'])->middleware('permission:applications.create');
    Route::post('/applications/{id}/decision', [C::class, 'decision'])->middleware('permission:applications.review');
    Route::post('/applications/{id}/cancel', [C::class, 'cancel'])->middleware('permission:applications.view');
    Route::put('/work-slots/{kind}/{id}', [C::class, 'saveSlot'])->middleware('permission:work_slots.manage');
    Route::get('/attendance', [C::class, 'attendance'])->middleware('permission:attendance.view');
    Route::post('/attendance', [C::class, 'punch'])->middleware('throttle:ams-face')->middleware('permission:attendance.record');
    Route::get('/attendance/{id}/photo/{side}', [C::class, 'photo'])->middleware('permission:attendance.view');
    Route::get('/teams', [C::class, 'teams'])->middleware('permission:teams.view');
    Route::post('/teams', [C::class, 'saveTeam'])->middleware('permission:teams.manage');
    Route::put('/teams/{id}/members', [C::class, 'members'])->middleware('permission:teams.manage');
    Route::get('/users', [C::class, 'users'])->middleware('permission:users.view');
    Route::post('/users/import', [C::class, 'importUsers'])->middleware('permission:users.import');
    Route::delete('/users/{id}', [C::class, 'deleteUser'])->middleware('permission:users.manage');
    Route::get('/applications/{id}/document', [C::class, 'document'])->middleware('permission:applications.view');
    Route::post('/users', [C::class, 'saveUser'])->middleware('permission:users.manage');
    Route::put('/users/{id}', [C::class, 'saveUser'])->middleware('permission:users.manage');
    Route::post('/face/challenges', [FaceController::class, 'start'])->middleware('throttle:ams-face');
    Route::post('/face/challenges/{id}/step', [FaceController::class, 'step'])->middleware('throttle:ams-face');
    Route::post('/face/challenges/{id}/capture', [FaceController::class, 'capture'])->middleware('throttle:ams-face');
    Route::post('/face/enroll', [FaceController::class, 'enroll'])->middleware('throttle:ams-face');
    Route::delete('/users/{id}/face', [C::class, 'deleteFace'])->middleware('permission:face.manage');
    Route::get('/leave-types', [C::class, 'leaveTypes'])->middleware('permission:leave_types.view');
    Route::put('/leave-types/{id}', [C::class, 'saveLeaveType'])->middleware('permission:leave_types.manage');
    Route::delete('/leave-types/{id}', [C::class, 'deleteLeaveType'])->middleware('permission:leave_types.manage');
    Route::post('/leave-types', [C::class, 'saveLeaveType'])->middleware('permission:leave_types.manage');
    Route::get('/calendar', [C::class, 'calendar'])->middleware('permission:calendar.view');
    Route::post('/calendar', [C::class, 'saveCalendar'])->middleware('permission:calendar.manage');
    Route::delete('/calendar/{id}', [C::class, 'deleteCalendar'])->middleware('permission:calendar.manage');
    Route::get('/audit', [C::class, 'audit'])->middleware('permission:audit.view');
});
