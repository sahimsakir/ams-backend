    Route::post('/leave-types', [C::class, 'saveLeaveType']);
    Route::get('/calendar', [C::class, 'calendar'])->middleware('permission:calendar.view');
    Route::post('/calendar', [C::class, 'saveCalendar']);
    Route::delete('/calendar/{id}', [C::class, 'deleteCalendar'])->middleware('permission:calendar.delete');
    Route::get('/audit', [C::class, 'audit'])->middleware('permission:audit.view');
});
