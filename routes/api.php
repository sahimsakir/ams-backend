    Route::post('/team-home-office', [TeamHomeOfficeController::class, 'store'])->middleware('permission:home_office.assign');
    Route::delete('/team-home-office/{id}', [TeamHomeOfficeController::class, 'destroy'])->middleware('permission:home_office.cancel');
